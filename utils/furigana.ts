const READING_KEYS = Object.keys(JAPANESE_READINGS).sort((a, b) => b.length - a.length);
const KANJI_RE = /[\u3400-\u9fff]/;

export function getFuriganaSegments(text: string): FuriganaSegment[] {
  const segments: FuriganaSegment[] = [];
  let index = 0;

  while (index < text.length) {
    const match = READING_KEYS.find((key) => text.startsWith(key, index));
    if (match) {
      segments.push({ text: match, reading: JAPANESE_READINGS[match] });
      index += match.length;
      continue;
    }

    const char = text[index];
    const previous = segments[segments.length - 1];
    if (previous && !previous.reading && !KANJI_RE.test(previous.text) && !KANJI_RE.test(char)) {
      previous.text += char;
    } else {
      segments.push({ text: char });
    }
    index += 1;
  }

  return segments;
}
